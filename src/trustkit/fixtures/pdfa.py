"""Builds the PDF/A-3b base for group F. A file is PDF/A only if veraPDF says so.

The font is Bitstream Vera as shipped with ReportLab, and the ICC profile is the sRGB
profile generated by Pillow. Neither is stored in this repository. pyHanko rewrites
/Metadata on every write and drops the PDF/A identification, so writers of these
files turn that off through keep_xmp.
"""

import datetime as dt
import io
from pathlib import Path

import reportlab
from PIL import ImageCms
from pyhanko.pdf_utils import embed, generic
from pyhanko.pdf_utils.reader import PdfFileReader
from pyhanko.pdf_utils.writer import BasePdfFileWriter, copy_into_new_writer
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen import canvas

ATTACHMENT_NAME = "synthetic-data.xml"
PAGE_AMOUNT = "1000.00"
OTHER_AMOUNT = "9000.00"
FILE_DATE = dt.datetime(2026, 1, 1, tzinfo=dt.timezone.utc)
FONT_NAME = "TrustKitVera"

XMP = (
    b'<?xpacket begin="\xef\xbb\xbf" id="W5M0MpCehiHzreSzNTczkc9d"?>'
    b'<x:xmpmeta xmlns:x="adobe:ns:meta/">'
    b'<rdf:RDF xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
    b'<rdf:Description rdf:about="" xmlns:pdfaid="http://www.aiim.org/pdfa/ns/id/">'
    b"<pdfaid:part>3</pdfaid:part><pdfaid:conformance>B</pdfaid:conformance>"
    b"</rdf:Description></rdf:RDF></x:xmpmeta>"
    b'<?xpacket end="w"?>'
)


def keep_xmp(writer: BasePdfFileWriter) -> None:
    """Stop pyHanko replacing /Metadata when this writer writes."""
    writer._update_meta = lambda: None


def synthetic_xml(amount: str) -> bytes:
    return (
        b'<?xml version="1.0" encoding="UTF-8"?>\n'
        b'<testDocument xmlns="urn:example.test:not-a-real-format">\n'
        b"  <note>TEST ONLY - synthetic data - Not For Production</note>\n"
        b"  <organization>Example Test Org</organization>\n"
        b"  <amount>" + amount.encode("ascii") + b"</amount>\n"
        b"</testDocument>\n"
    )


def embedded_file(writer: BasePdfFileWriter, data: bytes) -> embed.EmbeddedFileObject:
    return embed.EmbeddedFileObject.from_file_data(
        writer,
        data=data,
        compress=False,
        mime_type="application/xml",
        params=embed.EmbeddedFileParams(
            embed_size=True, creation_date=FILE_DATE, modification_date=FILE_DATE
        ),
    )


def _page() -> bytes:
    font = Path(reportlab.__file__).parent / "fonts" / "Vera.ttf"
    pdfmetrics.registerFont(TTFont(FONT_NAME, str(font)))
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pageCompression=0, invariant=1)
    pdf.setFont(FONT_NAME, 12)
    pdf.drawString(72, 750, "TEST ONLY - synthetic document - Not For Production")
    pdf.drawString(72, 720, "Example Test Org")
    pdf.drawString(72, 690, f"Amount: {PAGE_AMOUNT}")
    pdf.showPage()
    pdf.save()
    return buffer.getvalue()


def pdfa_with_xml(xml: bytes) -> bytes:
    """One page with an embedded font, an sRGB output intent, and xml as an attachment."""
    writer = copy_into_new_writer(PdfFileReader(io.BytesIO(_page())))
    keep_xmp(writer)
    name = generic.pdf_name
    profile = writer.add_object(
        generic.StreamObject(
            {name("/N"): generic.NumberObject(3)},
            stream_data=ImageCms.ImageCmsProfile(ImageCms.createProfile("sRGB")).tobytes(),
        )
    )
    intent = generic.DictionaryObject(
        {
            name("/Type"): name("/OutputIntent"),
            name("/S"): name("/GTS_PDFA1"),
            name("/OutputConditionIdentifier"): generic.TextStringObject("sRGB"),
            name("/DestOutputProfile"): profile,
        }
    )
    root = writer.root
    root[name("/OutputIntents")] = generic.ArrayObject([writer.add_object(intent)])
    root[name("/Metadata")] = writer.add_object(
        generic.StreamObject(
            {name("/Type"): name("/Metadata"), name("/Subtype"): name("/XML")},
            stream_data=XMP,
        )
    )
    embed.embed_file(
        writer,
        embed.FileSpec(
            file_spec_string=ATTACHMENT_NAME,
            file_name=ATTACHMENT_NAME,
            embedded_data=embedded_file(writer, xml),
            description="TEST ONLY synthetic data",
            af_relationship=name("/Data"),
        ),
    )
    # /AFRelationship makes pyHanko raise the version to 2.0. PDF/A-3 is based on PDF 1.7.
    writer.output_version = (1, 7)
    output = io.BytesIO()
    writer.write(output)
    return output.getvalue()
